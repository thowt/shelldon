package org.connectbot.shelldon.hostimport

import java.nio.ByteBuffer
import java.nio.charset.CharacterCodingException
import java.nio.charset.Charset
import java.nio.charset.CodingErrorAction

/**
 * Turns the bytes of an exported file into text. Windows tools write UTF-16 (registry exports),
 * UTF-8 with or without a byte order mark, or the ANSI code page (MobaXterm), so the byte order
 * mark decides first, then strict UTF-8, then Windows-1252. Nothing is ever guessed beyond that.
 */
internal object TextDecoding {
    fun decode(bytes: ByteArray): String {
        if (bytes.size >= 2 && bytes[0] == 0xFF.toByte() && bytes[1] == 0xFE.toByte()) {
            return String(bytes, 2, bytes.size - 2, Charsets.UTF_16LE)
        }
        if (bytes.size >= 2 && bytes[0] == 0xFE.toByte() && bytes[1] == 0xFF.toByte()) {
            return String(bytes, 2, bytes.size - 2, Charsets.UTF_16BE)
        }
        val start = if (bytes.size >= 3 && bytes[0] == 0xEF.toByte() && bytes[1] == 0xBB.toByte() && bytes[2] == 0xBF.toByte()) 3 else 0
        return try {
            Charsets.UTF_8.newDecoder()
                .onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT)
                .decode(ByteBuffer.wrap(bytes, start, bytes.size - start))
                .toString()
        } catch (_: CharacterCodingException) {
            String(bytes, start, bytes.size - start, WINDOWS_1252)
        }
    }

    private val WINDOWS_1252: Charset = Charset.forName("windows-1252")
}
